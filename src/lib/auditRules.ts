export function getRulesForSystems(systemIds: string): string {
    const rules: string[] = [];
    
    if (systemIds.includes('QMS') || systemIds === 'MULTI' || systemIds === 'INFO_FIVE') {
        rules.push(formatRule(QMS_RULES));
    }
    if (systemIds.includes('EMS') || systemIds === 'MULTI' || systemIds === 'INFO_FIVE') {
        rules.push(formatRule(EMS_RULES));
    }
    if (systemIds.includes('OHSMS') || systemIds === 'MULTI' || systemIds === 'INFO_FIVE') {
        rules.push(formatRule(OHSMS_RULES));
    }
    if (systemIds.includes('ISMS') || systemIds === 'INFO_MULTI' || systemIds === 'INFO_FIVE') {
        rules.push(formatRule(ISMS_RULES));
    }
    if (systemIds.includes('ITSMS') || systemIds === 'INFO_MULTI' || systemIds === 'INFO_FIVE') {
        rules.push(formatRule(ITSMS_RULES));
    }
    
    return rules.join('\\n\\n');
}

function formatRule(rule: AuditRule): string {
    let output = `【${rule.systemName} (${rule.systemId}) 专属评审规则与标准依据】\n`;
    output += `- 依据标准: ${rule.standards.join(', ')}\n`;
    output += `- 核心审查要求:\n`;
    rule.requirements.forEach((req, index) => {
        output += `  ${index + 1}. ${req}\n`;
    });
    return output;
}
